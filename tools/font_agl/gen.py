# Writes font/agl_data.odin: the Adobe Glyph List (2.0, as fontTools carries
# it) and the ITC Zapf Dingbats Glyph List, for glyph_name_runes.
#
#     python3 -I tools/font_agl/gen.py > font/agl_data.odin
from fontTools import agl

names = sorted(agl.LEGACY_AGL2UV, key=lambda s: s.encode())
text, name_at, runes, rune_at = "", [0], [], [0]
for n in names:
    text += n
    name_at.append(len(text))
    runes += agl.LEGACY_AGL2UV[n]
    rune_at.append(len(runes))
zapf = [0 if c == " " else ord(c) for c in agl._AGL_ZAPF_DINGBATS]
assert max(runes + zapf) < 0x10000 and len(text) < 1 << 32


def rows(values, per=16):
    return "\n".join("\t" + ", ".join(str(v) for v in values[i : i + per]) + "," for i in range(0, len(values), per))


print("// Generated by tools/font_agl/gen.py from fontTools' copy of the Adobe")
print("// Glyph List 2.0 and the ITC Zapf Dingbats Glyph List (Adobe, BSD 3-clause:")
print("// LICENSES/AGL-BSD-3.txt). Do not edit.")
print("package font")
print()
print("// The list's names, sorted by bytes, end to end; name i is")
print("// AGL_TEXT[AGL_NAME_AT[i]:AGL_NAME_AT[i + 1]], its characters")
print("// AGL_RUNES[AGL_RUNE_AT[i]:AGL_RUNE_AT[i + 1]].")
print("@(private, rodata)")
print("AGL_TEXT := " + " +\n\t".join('"%s"' % text[i : i + 96] for i in range(0, len(text), 96)))
print()
print("@(private, rodata)")
print("AGL_NAME_AT := [%d]u32{\n%s\n}" % (len(name_at), rows(name_at)))
print()
print("@(private, rodata)")
print("AGL_RUNE_AT := [%d]u16{\n%s\n}" % (len(rune_at), rows(rune_at)))
print()
print("@(private, rodata)")
print("AGL_RUNES := [%d]u16{\n%s\n}" % (len(runes), rows(runes)))
print()
print("// Zapf Dingbats' glyph aN's character, 0 for none.")
print("@(private, rodata)")
print("ZAPF_DINGBATS := [%d]u16{\n%s\n}" % (len(zapf), rows(zapf)))
